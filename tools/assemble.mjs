#!/usr/bin/env node
// Assembles every theme into a standalone, clone-ready repo:
//   shared/ (engine, setup form, wallet scripts, workflow)  +  layouts/<layout>/  +  generated theme
//
//   node tools/assemble.mjs                    → ../gsa-connect-<id>/ for every theme
//   node tools/assemble.mjs entomology law     → only those
//   OUT=/some/dir node tools/assemble.mjs
//
// Existing .git folders in the output are preserved, so re-running after edits is safe.
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { THEMES } from "./themes.mjs";
import { motif } from "./motifs.mjs";

const kit = resolve(import.meta.dirname, "..");
const owner = process.env.OWNER || "ank-man";
const outRoot = resolve(process.env.OUT || resolve(kit, ".."));
const only = process.argv.slice(2);
const themes = THEMES.filter((t) => !only.length || only.includes(t.id));
const readme = await readFile(resolve(kit, "docs/README.template.md"), "utf8");
const docs = ["WALLET-SETUP.md", "NFC-AND-PRINT.md"];
const baseCard = JSON.parse(await readFile(resolve(kit, "shared/card.json"), "utf8"));
const hasRsvg = (() => { try { execFileSync("rsvg-convert", ["--version"]); return true; } catch { return false; } })();

const LIST_FIELDS = ["publications", "projects", "education", "awards"];
const SANS = "system-ui, sans-serif", SERIF = "Georgia, serif", MONO = "ui-monospace, Menlo, monospace";
const fam = (f, fallback) => (f ? `"${f[0]}", ${fallback}` : undefined);

export function themeCss(t) {
  const p = t.palette;
  if (!p && !t.fonts && !t.motif) return "/* Uses the layout's default look. */\n";
  const [h, b, m] = t.fonts || [];
  const mot = t.motif ? motif(...t.motif) : undefined;
  const common = { "--accent": p?.accent, "--ink": p?.ink, "--muted": p?.muted, "--bg": p?.bg, "--line": p?.line, "--motif": mot };
  const card = p?.card || [];
  const map = {
    classic: { ...common, "--accent-dark": p?.accent2, "--surface": p?.surface, "--chip": p?.soft, "--strong": p?.strong, "--font-head": fam(h, SANS), "--font-body": fam(b, SANS), "--head-case": t.head?.case },
    scholar: { ...common, "--paper": p?.bg, "--rule": p?.line, "--surface": p?.surface, "--serif": fam(h, SERIF), "--sans": fam(b, SANS) },
    minimal: { ...common, "--tile": p?.soft, "--font-head": fam(h, SANS), "--font-body": fam(b, SANS) },
    midnight: { ...common, "--accent-2": p?.accent2, "--card-a": card[0], "--card-b": card[1], "--card-c": card[2], "--font-body": fam(b || h, SANS), "--mono": fam(m, MONO) },
    officer: { ...common, "--accent-dark": p?.accent2, "--card": p?.surface, "--strong": p?.strong, "--soft": p?.soft, "--cond": fam(h, SANS), "--font-body": fam(b, SANS) },
    terminal: { ...common, "--accent-2": p?.accent2, "--surface": p?.surface, "--mono": fam(h, MONO) },
    portfolio: { ...common, "--accent-2": p?.accent2, "--surface": p?.surface, "--font-head": fam(h, SANS), "--font-body": fam(b, SANS), "--head-case": t.head?.case }
  }[t.layout];
  const decl = Object.entries(map).filter(([, v]) => v != null).map(([k, v]) => `  ${k}: ${v};`).join("\n");
  return `/* ${t.name} theme. Generated by tools/assemble.mjs; edit freely. */\n:root {\n${decl}\n}\n`;
}

function fontsHref(fonts) {
  const fams = [...new Map(fonts.map((f) => [f[0], f])).values()];
  return "https://fonts.googleapis.com/css2?" + fams.map(([n, w]) => `family=${n.replace(/ /g, "+")}${w && w !== "400" ? `:wght@${w}` : ""}`).join("&") + "&display=swap";
}

function buildCard(t) {
  const card = structuredClone(baseCard);
  const persona = t.persona || {};
  if (Object.keys(persona).length) {
    for (const k of LIST_FIELDS) card[k] = [];
    card.slug = persona.name.toLowerCase().replace(/[^a-z]+/g, "-");
    card.email = "yourname@uga.edu";
    card.bio = `Graduate student at the University of Georgia. ${persona.headline || ""} Open to collaborations, mentoring and good conversations.`;
    card.education = [{ degree: persona.title, school: "University of Georgia", years: "2024 – present" }];
    card.photo = "";
    card.gsaRole = "GSA Member";
    card.officeHours = "By appointment · use the booking link";
    card.badgeLabel = "GSA Member";
  }
  Object.assign(card, persona);
  const p = t.palette;
  card.wallet = {
    ...card.wallet,
    ...(p && { backgroundColor: (p.card?.[1]) || p.accent, foregroundColor: "#FFFFFF", labelColor: p.soft || "#EDEDED" }),
    ...(t.wallet || {})
  };
  return card;
}

function iconSvgs(accent, bg = "#ffffff") {
  const glyph = (s) => `<g fill="none" stroke-linecap="round" stroke-width="5"><circle cx="22" cy="32" r="4" fill="${s}" stroke="none"/><path d="M30 22a14 14 0 0 1 0 20M37 15a24 24 0 0 1 0 34M44 8a34 34 0 0 1 0 48" stroke="${s}"/></g>`;
  return {
    favicon: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="${accent}"/>${glyph(bg)}</svg>`,
    maskable: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" fill="${accent}"/><g transform="translate(9.6 9.6) scale(.7)">${glyph(bg)}</g></svg>`,
    walletLogo: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><circle cx="32" cy="32" r="32" fill="${accent}"/><g transform="translate(8 8) scale(.75)">${glyph(bg)}</g></svg>`
  };
}

async function writeIcons(out, accent) {
  const s = iconSvgs(accent);
  await writeFile(resolve(out, "favicon.svg"), s.favicon);
  if (!hasRsvg) return;
  const png = (svg, size, file) => execFileSync("rsvg-convert", ["-w", String(size), "-h", String(size), "-o", resolve(out, file)], { input: svg });
  png(s.maskable, 192, "assets/icon-192.png");
  png(s.maskable, 512, "assets/icon-512.png");
  png(s.maskable, 180, "assets/apple-touch-icon.png");
  png(s.walletLogo, 660, "assets/wallet-logo.png");
  png(s.favicon, 29, "wallet/apple/model.pass/icon.png");
  png(s.favicon, 58, "wallet/apple/model.pass/icon@2x.png");
  png(s.favicon, 87, "wallet/apple/model.pass/icon@3x.png");
}

for (const t of themes) {
  t.repo ||= `gsa-connect-${t.id}`;
  const out = resolve(outRoot, t.repo);
  await mkdir(out, { recursive: true });
  for (const f of await readdir(out)) if (f !== ".git") await rm(resolve(out, f), { recursive: true, force: true });

  await cp(resolve(kit, "shared"), out, { recursive: true });
  await cp(resolve(kit, "layouts", t.layout), out, { recursive: true });

  // theme.css + fonts + theme colour in index.html
  await writeFile(resolve(out, "css/theme.css"), themeCss(t));
  let html = await readFile(resolve(out, "index.html"), "utf8");
  html = html.replace('<link rel="stylesheet" href="css/style.css">', '<link rel="stylesheet" href="css/style.css">\n  <link rel="stylesheet" href="css/theme.css">');
  if (t.fonts) html = html.replace(/<link href="https:\/\/fonts\.googleapis\.com\/css2\?[^"]+" rel="stylesheet">/, `<link href="${fontsHref(t.fonts)}" rel="stylesheet">`);
  const themeColor = t.palette ? (t.layout === "midnight" || t.layout === "terminal" ? t.palette.bg : t.layout === "classic" ? t.palette.accent : t.palette.bg) : null;
  if (themeColor) html = html.replace(/<meta name="theme-color" content="[^"]*">/, `<meta name="theme-color" content="${themeColor}">`);
  html = html.replace(/<!-- (TEMPLATE|LAYOUT): ([^—]+)—/, `<!-- ${t.name} theme · $2layout —`);
  await writeFile(resolve(out, "index.html"), html);

  const card = buildCard(t);
  await writeFile(resolve(out, "card.json"), JSON.stringify(card, null, 2) + "\n");
  if (t.palette) await writeIcons(out, t.palette.accent);

  const manifest = JSON.parse(await readFile(resolve(out, "manifest.webmanifest"), "utf8"));
  manifest.name = `${t.name} · GSA Connect`;
  if (t.palette) { manifest.theme_color = themeColor; manifest.background_color = t.palette.bg; }
  await writeFile(resolve(out, "manifest.webmanifest"), JSON.stringify(manifest, null, 2) + "\n");

  const pkg = JSON.parse(await readFile(resolve(out, "package.json"), "utf8"));
  pkg.name = t.repo;
  pkg.description = `${t.name}: UGA GSA Connect digital business card. Powered by ScholarTap.`;
  await writeFile(resolve(out, "package.json"), JSON.stringify(pkg, null, 2) + "\n");

  const meta = { ...t, name: `GSA Connect · ${t.name}`, layoutName: t.layout[0].toUpperCase() + t.layout.slice(1) };
  await writeFile(resolve(out, "README.md"), readme.replace(/\{\{(\w+)\}\}/g, (_, k) => meta[k] ?? "").replaceAll("OWNER", owner));
  await mkdir(resolve(out, "docs"), { recursive: true });
  for (const d of docs) await cp(resolve(kit, "docs", d), resolve(out, "docs", d));
  await cp(resolve(kit, "LICENSE"), resolve(out, "LICENSE"));
  try { await cp(resolve(kit, "docs/screenshots", `${t.id}.jpg`), resolve(out, "docs/preview.jpg")); } catch {}
  console.log(`✓ ${t.repo.padEnd(38)} ${t.layout}`);
}
console.log(`\n${themes.length} repos → ${outRoot}`);
